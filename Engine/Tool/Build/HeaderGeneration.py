from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
from Util.FileGeneration import update_generated_file

NOTICE = """// This file is auto-generated by HeaderGeneration.py. Do not edit directly."""


def _is_header_file(path: Path) -> bool:
	return path.suffix.lower() in {".h", ".hpp", ".hh", ".hxx"}


def _is_directory_aggregate_header(path: Path) -> bool:
	return _is_header_file(path) and path.stem.startswith("__")


def generate_directory_header(directory_path: str | Path) -> Path:
	"""
	Create or update a directory aggregate header named "__<DirectoryName>.hpp".

	Rules:
	- Includes all header files in the given directory (excluding the generated
	  aggregate file itself and any other aggregate headers that start with "__").
	- Scans only first-level subdirectories.
	- In each first-level subdirectory, includes only existing aggregate headers
	  that follow the "__" naming convention.

	Args:
		directory_path: Directory to scan.

	Returns:
		The path to the generated aggregate header.
	"""
	directory = Path(directory_path).resolve()
	if not directory.exists() or not directory.is_dir():
		raise ValueError(f"Path is not a directory: {directory}")

	output_name = f"__{directory.name}.hpp"
	output_path = directory / output_name

	includes: list[str] = []

	# Include direct header files from this directory.
	for item in sorted(directory.iterdir(), key=lambda p: p.name.lower()):
		if not item.is_file() or not _is_header_file(item):
			continue

		if item.name == output_name:
			continue

		if item.name.lower() in {"pch.hpp", "pch.h"}:
			continue

		if item.stem.startswith("__"):
			continue

		includes.append(f'#include "{item.name}"')

	# Include first-level subdirectory aggregate headers only.
	for subdir in sorted(directory.iterdir(), key=lambda p: p.name.lower()):
		if not subdir.is_dir():
			continue

		for item in sorted(subdir.iterdir(), key=lambda p: p.name.lower()):
			if not item.is_file() or not _is_directory_aggregate_header(item):
				continue

			includes.append(f'#include "{subdir.name}/{item.name}"')

	contents = f"{NOTICE}\n#pragma once\n\n"
	if includes:
		contents += "\n".join(includes) + "\n"

	update_generated_file(str(output_path), contents)
	return output_path


def _make_parser() -> argparse.ArgumentParser:
	parser = argparse.ArgumentParser(
		description=(
			"Generate an aggregate header named __<DirectoryName>.hpp from headers "
			"in a directory and first-level subdirectory aggregate headers."
		)
	)
	parser.add_argument(
		"path",
		help="Target directory to generate the aggregate header for.",
	)
	return parser


def main() -> int:
	parser = _make_parser()
	args = parser.parse_args()

	try:
		output_path = generate_directory_header(args.path)
	except ValueError as error:
		print(f"Error: {error}")
		return 1

	print(f"Generated: {output_path}")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
